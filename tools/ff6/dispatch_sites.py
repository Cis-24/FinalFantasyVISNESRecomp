"""Dispatch-site list (PLAN 3.6): generate, load and check tools/ff6/dispatch_sites.toml.

The TOML holds only labels, file/line keys and counts. Addresses come from the ld65
debug file; every site is verified against the ROM opcode (7C/FC = (abs,x), 6C = (abs)).
Usage:
  gen:   python dispatch_sites.py gen --src <ff6/src> --dbg <dbg> --out dispatch_sites.toml
  check: python dispatch_sites.py check --sites dispatch_sites.toml --dbg <dbg> --rom <rom>
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import export_ca65_authority as ex

SITE = re.compile(r'^\s*(?:@?\w+:)?\s*(jmp|jsr)\s+(\(.*?\))\s*(?:;.*)?$', re.I)
TABLE_X = re.compile(r'^\((?:near)?(?:\.loword\()?(@?\w+)\)?(?:([+-])(\$?[0-9a-fA-F]+))?,x\)$', re.I)
RAM_PTR = re.compile(r'^\((\$[0-9a-fA-F]{4})\)$')
RAM_TBL = re.compile(r'^\((\$[0-9a-fA-F]{4}),x\)$')
LDA_TBL = re.compile(r'lda\s+f:(\w+)\s*,\s*x', re.I)
OPCODE = {"x": {"jmp": 0x7C, "jsr": 0xFC}, "ptr": {"jmp": 0x6C, "jsr": 0x6C}}


def num(t):
    return int(t[1:], 16) if t.startswith("$") else int(t)


def scan(src_root):
    """Yield one record per indirect jmp/jsr in the ff6 sources (document order)."""
    for path in sorted(Path(src_root).rglob("*.asm")):
        rel = path.relative_to(src_root).as_posix()
        stack, label, occ = [], "", {}
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        for n, raw in enumerate(lines, 1):
            code = raw.split(";", 1)[0]
            m = re.match(r'\s*\.proc\s+(\w+)', code)
            if m:
                stack.append(m.group(1))
            elif re.match(r'\s*\.endproc', code) and stack:
                stack.pop()
            else:
                lm = re.match(r'^(\w+):', code)
                if lm and not lm.group(1).startswith("_"):
                    label = lm.group(1)
            m = SITE.match(raw)
            if not m:
                continue
            op, operand = m.group(1).lower(), m.group(2).replace(" ", "")
            proc = stack[-1] if stack else label
            occ[proc] = occ.get(proc, 0) + 1
            rec = dict(file=rel, line=n, proc=proc, occurrence=occ[proc], op=op)
            t = TABLE_X.match(operand)
            if t:
                off = num(t.group(3)) if t.group(3) else 0
                rec.update(kind="table", table=t.group(1), offset=-off if t.group(2) == "-" else off)
            elif RAM_TBL.match(operand):
                rec.update(kind="ram_table", table=RAM_TBL.match(operand).group(1), offset=0)
            elif RAM_PTR.match(operand):
                tbl = ""
                for k in range(n - 2, max(n - 9, 0), -1):
                    lm = LDA_TBL.search(lines[k].split(";")[0])
                    if lm:
                        tbl = lm.group(1)
                        break
                rec.update(kind="ptrtail" if op == "jmp" else "ptrcall", table=tbl, ptr=operand.strip("()"), offset=0)
            else:
                rec.update(kind="unparsed", operand=operand)
            yield rec


def table_info(dbg, name, site_file, site_line=None):
    """(address, entry count) for a table label, or None. Count = consecutive typed .addr entries.

    A label defined in several modules (battle and menu both have MaxHPMPTbl) resolves to the
    symbol the site line references; failing that, to the one in the site file's module. Still
    ambiguous: None, never the first candidate.
    """
    fid = next((i for i, f in dbg["files"].items() if f.lstrip("./") == "src/" + site_file), None)
    mods = {i for i, m in dbg["mods"].items() if m["file"] == fid}
    cands = [s for s in dbg["syms"] if s["name"] == name]
    if not cands:
        return None
    if len(cands) > 1:
        refd = [s for s in cands
                if any(dbg.get("line_loc", {}).get(r) == (fid, site_line) for r in s.get("ref", []))]
        same = [s for s in cands if dbg["scopes"].get(s["scope"], {}).get("mod") in mods]
        cands = refd if len(refd) == 1 else same
        if len(cands) != 1:
            return None
    pc = cands[0]["val"]
    ends = sorted(s["val"] for s in dbg["syms"] if s["val"] > pc and not s["name"].startswith("LOCAL"))
    limit = ends[0] if ends else pc + 2
    typed = {dbg["segs"][sp["seg"]]["start"] + sp["start"] for sp in dbg["spans"].values()
             if sp["typed"] and sp["size"] == 2}
    n, a = 0, pc
    while a < limit and a in typed:
        n, a = n + 1, a + 2
    return pc, n or (limit - pc) // 2


def dump(recs, dbg):
    fids = {i: f.lstrip("./") for i, f in dbg["files"].items()}
    assembled = {(fids.get(fid), ln) for fid, ln, lt, sps in dbg["lines"].values()
                 if lt != 2 and any(x in dbg["spans"] for x in sps)}
    out = ["# Dispatch sites of FF6 (generated by dispatch_sites.py gen, then hand-reviewed).",
           "# Keys: file/line (relative to ff6/src), proc, occurrence. Addresses are resolved from the .dbg.",
           "# count = table entries (nullslots are skipped by the resolver); offset = bytes added to the table label.",
           "# in_build = false: the source line is not assembled into the EN ROM (e.g. under .if !LANG_EN).",
           ""]
    for r in recs:
        out += ["[[site]]", f'file = "{r["file"]}"', f'line = {r["line"]}', f'proc = "{r["proc"]}"',
                f'occurrence = {r["occurrence"]}', f'op = "{r["op"]}"', f'kind = "{r["kind"]}"']
        if r["kind"] == "unparsed":
            out.append(f'operand = "{r["operand"]}"')
        else:
            out.append(f'table = "{r["table"]}"')
            info = None if r["kind"] == "ram_table" or not r["table"] else table_info(dbg, r["table"], r["file"], r["line"])
            out.append(f'count = {info[1] if info else 0}')
            out.append(f'offset = {r["offset"]}')
            if "ptr" in r:
                out.append(f'ptr = "{r["ptr"]}"')
            if ("src/" + r["file"], r["line"]) in dbg["ram_lines"]:
                out.append('tier = "ram"')            # runs from WRAM: interpreter tier, no authority
            elif not info or ("src/" + r["file"], r["line"]) not in assembled:
                out.append("in_build = false")
        out.append("")
    return "\n".join(out)


def load(path):
    import tomllib
    return tomllib.loads(Path(path).read_text(encoding="utf-8")).get("site", [])


def check(sites, dbg, rom):
    """Resolve each site to an address and verify the opcode; returns (ok, problems)."""
    fids = {i: f.lstrip("./") for i, f in dbg["files"].items()}
    by_line = {}
    for fid, ln, lt, sps in dbg["lines"].values():
        for s in sps:
            sp = dbg["spans"].get(s)
            if sp and lt != 2:
                by_line.setdefault((fids.get(fid), ln), []).append(dbg["segs"][sp["seg"]]["start"] + sp["start"])
    ok, problems, ram = [], [], []
    for s in sites:
        addrs = by_line.get(("src/" + s["file"], s["line"]))
        if s.get("tier") == "ram":
            if ("src/" + s["file"], s["line"]) not in dbg["ram_lines"]:
                problems.append((s, "marked ram but not in a RAM segment"))
            else:
                ram.append(s)
            continue
        if not addrs:
            problems.append((s, "not in this build" if s.get("in_build") is False else "no span for source line"))
            continue
        pc = min(addrs)
        seg = next(g for g in dbg["segs"].values() if g["start"] <= pc < g["start"] + g["size"])
        op = rom[seg["ooffs"] + pc - seg["start"]]
        want = OPCODE["ptr" if s["kind"] in ("ptrtail", "ptrcall", "ptrlist") else "x"][s["op"]]
        if op != want:
            problems.append((s, f"opcode {op:02X} at {pc:06X}, expected {want:02X}"))
        else:
            ok.append((s, pc))
    return ok, problems, ram


def build_dispatches(sites, dbg, rows, rom):
    """Authority `dispatches` for all ROM sites. Returns (dispatches, n_sites, dropped_target_notes).

    jmp -> ptrtail, jsr -> ptrcall. Targets are the table words (nullslots skipped, entries
    below a positive `offset` unreachable) resolved in the site's execution bank. Targets that
    are not authoritative instruction starts are dropped and reported, never invented.
    kind = "ptrlist": a pointer in RAM with no table; `targets` names every label the source
    stores into it (each must be a unique label in the site's bank).
    """
    ok, _problems, _ram = check(sites, dbg, rom)
    out, dropped = [], []
    segs = list(dbg["segs"].values())
    for s, pc in ok:
        if s["kind"] == "ptrlist":
            targets = set()
            for name in s.get("targets", []):
                cands = [y["val"] for y in dbg["syms"] if y["name"] == name]
                if len(cands) != 1 or cands[0] >> 16 != pc >> 16:
                    dropped.append(f"{pc:06X} {s['file']}:{s['line']} {name} not a unique label in bank {pc >> 16:02X}")
                elif rows.get(cands[0], {}).get("kind") != "code":
                    dropped.append(f"{pc:06X} {s['file']}:{s['line']} {name} -> {cands[0]:06X} not an instruction")
                else:
                    targets.add(cands[0])
            if targets:
                out.append(dict(site_pc24=f"0x{pc:06X}", kind="ptrcall" if s["op"] == "jsr" else "ptrtail",
                                targets=[f"0x{t:06X}" for t in sorted(targets)]))
            continue
        if not s.get("table") or s.get("count", 0) <= 0:
            dropped.append(f"{pc:06X} {s['file']}:{s['line']} no table/count")
            continue
        info = table_info(dbg, s["table"], s["file"], s["line"])
        if not info:
            dropped.append(f"{pc:06X} {s['file']}:{s['line']} table {s['table']} not found or ambiguous")
            continue
        tpc, count = info
        first = max(0, s.get("offset", 0)) // 2
        seg = next(g for g in segs if g["start"] <= tpc < g["start"] + g["size"])
        targets = set()
        for i in range(first, s.get("count", count)):
            o = seg["ooffs"] + tpc - seg["start"] + 2 * i
            word = rom[o] | rom[o + 1] << 8
            if word == 0:
                continue
            t = (pc & 0xFF0000) | word
            if rows.get(t, {}).get("kind") == "code":
                targets.add(t)
            else:
                dropped.append(f"{pc:06X} {s['file']}:{s['line']} {s['table']}[{i}] -> {t:06X} not an instruction")
        if targets:
            out.append(dict(site_pc24=f"0x{pc:06X}", kind="ptrcall" if s["op"] == "jsr" else "ptrtail",
                            targets=[f"0x{t:06X}" for t in sorted(targets)]))
    return out, len(ok), dropped


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("--src", required=True, type=Path)
    g.add_argument("--dbg", required=True, type=Path)
    g.add_argument("--out", required=True, type=Path)
    c = sub.add_parser("check")
    c.add_argument("--sites", required=True, type=Path)
    c.add_argument("--dbg", required=True, type=Path)
    c.add_argument("--rom", required=True, type=Path)
    a = ap.parse_args()
    dbg = ex.parse_dbg(a.dbg)
    if a.cmd == "gen":
        recs = list(scan(a.src))
        a.out.write_text(dump(recs, dbg), encoding="utf-8")
        print(f"{len(recs)} sites")
        return 0
    ok, problems, ram = check(load(a.sites), dbg, a.rom.read_bytes())
    for s, why in problems:
        print(f"{s['file']}:{s['line']} {why}")
    print(f"{len(ok)} resolved, {len(ram)} ram-resident, {len(problems)} not assembled/problems")
    return 1 if [p for p in problems if p[1] != "not in this build"] else 0


if __name__ == "__main__":
    sys.exit(main())
